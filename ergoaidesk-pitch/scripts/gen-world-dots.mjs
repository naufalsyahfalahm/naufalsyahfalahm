// Generates src/generated/worldDots.ts: a uniform grid of land dots (equirectangular).
// Source: Natural Earth 110m land via the `world-atlas` package (public domain).
// Pure land/sea mask. No data is attached to any dot, so nothing can be shaded or read as prevalence.
import { createRequire } from "node:module";
import { mkdirSync, writeFileSync } from "node:fs";
import { geoContains } from "d3-geo";
import { feature } from "topojson-client";

const require = createRequire(import.meta.url);
const topo = require("world-atlas/land-110m.json");
const land = feature(topo, topo.objects.land);

const STEP = 3.0; // degrees between dot centres
const LAT_MIN = -56;
const LAT_MAX = 80;
const dots = [];
for (let lat = LAT_MAX; lat >= LAT_MIN; lat -= STEP) {
  for (let lon = -180; lon < 180; lon += STEP) {
    if (geoContains(land, [lon + STEP / 2, lat - STEP / 2])) {
      dots.push([
        Number(((lon + STEP / 2 + 180) / 360).toFixed(4)),
        Number(((LAT_MAX - (lat - STEP / 2)) / (LAT_MAX - LAT_MIN)).toFixed(4)),
      ]);
    }
  }
}
mkdirSync("src/generated", { recursive: true });
writeFileSync(
  "src/generated/worldDots.ts",
  `// AUTO-GENERATED by scripts/gen-world-dots.mjs. Do not edit.\n// Normalised [x,y] in 0..1; land mask only (Natural Earth 110m, public domain).\n` +
    `export const WORLD_DOT_ASPECT = ${(360 / (LAT_MAX - LAT_MIN)).toFixed(4)};\n` +
    `export const WORLD_DOTS: ReadonlyArray<readonly [number, number]> = ${JSON.stringify(dots)};\n`,
);
console.log(`worldDots: ${dots.length} dots`);
