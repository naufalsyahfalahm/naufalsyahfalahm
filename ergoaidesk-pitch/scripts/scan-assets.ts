/**
 * Scans public/ for the optional assets named in src/config.ts and writes src/generated/assets.ts.
 * Run automatically by `npm run dev|render|still|check`. Re-run after adding or removing a file.
 * Missing file => the video renders a labelled placeholder (or omits the optional layer); never an error.
 */
import { execFileSync } from "node:child_process";
import { existsSync, mkdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { FILES, RECORDINGS } from "../src/config";

const PUBLIC = join(process.cwd(), "public");
type Info = { exists: boolean; width?: number; height?: number; durationSec?: number; fps?: number };

const paths = new Set<string>([
  ...Object.values(FILES),
  ...Object.values(RECORDINGS).map((r) => r.file),
]);

function probe(file: string): Partial<Info> {
  try {
    const out = execFileSync(
      "ffprobe",
      ["-v", "error", "-show_entries", "stream=width,height,r_frame_rate:format=duration", "-of", "json", file],
      { encoding: "utf8" },
    );
    const j = JSON.parse(out);
    const v = (j.streams ?? []).find((s: { width?: number }) => s.width);
    const [n, d] = String(v?.r_frame_rate ?? "0/1").split("/").map(Number);
    return {
      width: v?.width,
      height: v?.height,
      fps: d ? n / d : undefined,
      durationSec: j.format?.duration ? Number(j.format.duration) : undefined,
    };
  } catch {
    return {};
  }
}

function pngSize(file: string): Partial<Info> {
  const b = readFileSync(file);
  if (b.length > 24 && b.toString("ascii", 1, 4) === "PNG") {
    return { width: b.readUInt32BE(16), height: b.readUInt32BE(20) };
  }
  return probe(file);
}

const info: Record<string, Info> = {};
for (const p of [...paths].sort()) {
  const abs = join(PUBLIC, p);
  if (!existsSync(abs) || statSync(abs).size === 0) {
    info[p] = { exists: false };
    continue;
  }
  info[p] = { exists: true, ...(/\.png$/i.test(p) ? pngSize(abs) : /\.(mp4|mov|webm|mp3|wav|m4a|jpg|jpeg)$/i.test(p) ? probe(abs) : {}) };
}

// ---- validation.csv (optional). Required columns: system_score, expert_score, physical_score, psychological_score
type Row = { system_score: number; expert_score: number; physical_score: number; psychological_score: number };
let rows: Row[] | null = null;
const csvAbs = join(PUBLIC, FILES.validationCsv);
const notes: string[] = [];
if (existsSync(csvAbs)) {
  const lines = readFileSync(csvAbs, "utf8").replace(/^﻿/, "").split(/\r?\n/).filter((l) => l.trim());
  const sep = lines[0]?.includes(";") && !lines[0].includes(",") ? ";" : ",";
  const head = (lines[0] ?? "").split(sep).map((h) => h.trim().toLowerCase());
  const need = ["system_score", "expert_score", "physical_score", "psychological_score"];
  const idx = need.map((c) => head.indexOf(c));
  if (idx.some((i) => i < 0)) {
    notes.push(`validation.csv ignored: missing column(s) ${need.filter((_, k) => idx[k] < 0).join(", ")}`);
  } else {
    const out: Row[] = [];
    let dropped = 0;
    for (const l of lines.slice(1)) {
      const c = l.split(sep).map((x) => x.trim());
      const v = idx.map((i) => (c[i] === undefined || c[i] === "" ? NaN : Number(c[i])));
      if (v.every(Number.isFinite)) {
        out.push({ system_score: v[0], expert_score: v[1], physical_score: v[2], psychological_score: v[3] });
      } else dropped++;
    }
    rows = out;
    notes.push(`validation.csv: ${out.length} complete row(s) used, ${dropped} row(s) dropped (missing/non-numeric)`);
  }
}

mkdirSync("src/generated", { recursive: true });
writeFileSync(
  "src/generated/assets.ts",
  `// AUTO-GENERATED by scripts/scan-assets.ts. Do not edit.\n` +
    `export type AssetInfo = { exists: boolean; width?: number; height?: number; durationSec?: number; fps?: number };\n` +
    `export type ValidationRow = { system_score: number; expert_score: number; physical_score: number; psychological_score: number };\n` +
    `export const ASSETS: Record<string, AssetInfo> = ${JSON.stringify(info, null, 2)};\n` +
    `export const VALIDATION_ROWS: ValidationRow[] | null = ${JSON.stringify(rows)};\n`,
);

for (const [p, i] of Object.entries(info)) {
  const dims = i.width ? ` ${i.width}x${i.height}${i.durationSec ? ` ${i.durationSec.toFixed(2)}s` : ""}` : "";
  console.log(`${i.exists ? "found  " : "MISSING"} public/${p}${dims}`);
}
for (const n of notes) console.log(n);
