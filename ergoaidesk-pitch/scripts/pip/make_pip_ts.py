import json
FPS=30; FADE=0.3; HOLD_MAX=3.0; CLOSE0=160.0; END=180.0
seg=sorted(json.load(open("work/segments.json")),key=lambda s:s["start"])
clips=[]
for s in seg:
    if clips and clips[-1]["spk"]==s["spk"] and s["start"]-clips[-1]["end"]<0.2: clips[-1]["end"]=s["end"]
    else: clips.append(dict(spk=s["spk"],start=s["start"],end=s["end"]))
vis={"tya":[],"zaky":[]}   # list of [t_in0,t_in1,t_out0,t_out1]
cur={}   # open interval per speaker: [in0,in1]
def open_(spk,i0,i1): cur[spk]=[i0,i1]
def close_(spk,o0,o1):
    i0,i1=cur.pop(spk); vis[spk].append([i0,i1,o0,o1])
for i,c in enumerate(clips):
    spk=c["spk"]
    if i==0: open_(spk,0.0,FADE)
    else:
        p=clips[i-1]; g=c["start"]-p["end"]
        if g>HOLD_MAX:
            if p["spk"] in cur: close_(p["spk"],p["end"]+0.5,p["end"]+0.5+FADE)
            open_(spk,c["start"]-0.5-FADE,c["start"]-0.5)
        elif p["spk"]!=spk:
            m=(p["end"]+c["start"])/2
            close_(p["spk"],m-FADE/2,m+FADE/2); open_(spk,m-FADE/2,m+FADE/2)
        else:
            if spk not in cur: open_(spk,c["start"]-0.5-FADE,c["start"]-0.5)
for spk in list(cur): 
    last=[c for c in clips if c["spk"]==spk][-1]
    close_(spk,last["end"]+0.5,last["end"]+0.5+FADE)
def kf(iv):
    pts=[]
    for i0,i1,o0,o1 in iv: pts+= [(i0,0),(i1,1),(o0,1),(o1,0)]
    pts.sort(); 
    # merge contiguous
    out=[]
    for t,v in pts:
        if out and abs(out[-1][0]-t)<1e-6 and out[-1][1]==v: continue
        out.append((t,v))
    return [[round(t*FPS),v] for t,v in out]
fr=lambda t:round(t*FPS)
tracks={
 "A":{"file":"pip/face_A_aligned.mp4","right":kf(vis["tya"])+[[fr(CLOSE0),0],[fr(CLOSE0+FADE),1],[fr(END),1]],"left":[]},
 "B":{"file":"pip/face_B_aligned.mp4","right":kf(vis["zaky"]),"left":[[fr(169.57),0],[fr(169.57+FADE),1],[fr(END),1]]},
}
# drop keyframes of right-B/A that fall in/after the closing (closing handled explicitly)
for k in tracks: tracks[k]["right"]=[p for p in tracks[k]["right"] if p[0]<fr(CLOSE0)] + ([[fr(CLOSE0),0],[fr(CLOSE0+FADE),1],[fr(END),1]] if k=="A" else [[fr(CLOSE0),0]])
ts="// Generated by work/make_pip_ts.py from the speaker map / alignment (see out/report.md). Frames at 30 fps.\n"
ts+="export const PIP_TRACKS = "+json.dumps(tracks)+" as const;\n"
open("src/generated/pip.ts","w").write(ts)
print(json.dumps({k:v["right"] for k,v in tracks.items()}))
for c in clips: print(c)
