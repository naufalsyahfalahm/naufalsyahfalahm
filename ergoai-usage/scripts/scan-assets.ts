// Records which optional files exist so a missing file never errors. Run before dev/render.
import { existsSync, mkdirSync, writeFileSync } from "node:fs";

const voiceover = existsSync("public/audio/voiceover.wav");
mkdirSync("src/generated", { recursive: true });
writeFileSync(
  "src/generated/assets.ts",
  `// Generated by scripts/scan-assets.ts. Do not edit.\nexport const assets = { voiceover: ${voiceover} } as const;\n`,
);
console.log(`voiceover.wav present: ${voiceover}`);
